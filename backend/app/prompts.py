def _format_article(a: KBArticle) -> str:
    head = f"[id={a.id}] {a.title}"
    if a.price_rub is not None:
        head += f" — цена {a.price_rub:,} ₽".replace(",", " ")
    return f"{head}\n{a.content.strip()}"


def _format_message(author: str, text: str) -> str:
    return f"[{'Клиент' if author == 'client' else 'Менеджер'}] {text.strip()}"


def build_user_prompt(dialog: Dialog, articles: list[KBArticle], notes: list[str] = ()) -> str:
    pending = dialog.pending_client_messages()
    history = dialog.messages[: len(dialog.messages) - len(pending)]

    kb = "\n\n".join(_format_article(a) for a in articles) or "(подходящих статей не найдено)"
    hist = "\n".join(_format_message(m.author, m.text) for m in history) or "(диалог только начался)"
    new = "\n".join(_format_message(m.author, m.text) for m in pending)
    name = dialog.contact_name or "неизвестно"

    return (
        f"<knowledge_base>\n{kb}\n</knowledge_base>\n\n"
        f"<client_name>{name}</client_name>\n\n"
        f"<dialog_history>\n{hist}\n</dialog_history>\n\n"
        f"<new_client_messages>\n{new}\n</new_client_messages>\n\n"
        + (f"<signals>\n{chr(10).join(notes)}\n</signals>\n\n" if notes else "")
        + "Верни JSON по схеме."
    )
